import assert from 'node:assert/strict';
const base = process.env.TEST_BASE_URL || 'http://localhost:3000';
function client() {
 const cookies = new Map();
 return async (path, method = 'GET', body, expected = 200) => {
  const headers = { 'Content-Type': 'application/json', Origin: base, Cookie: [...cookies].map(([k, v]) => `${k}=${v}`).join('; ') };
  const response = await fetch(`${base}/api/${path}`, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) });
  for (const header of response.headers.getSetCookie()) { const item = header.split(';')[0]; const index = item.indexOf('='); cookies.set(item.slice(0, index), item.slice(index + 1)); }
  const data = await response.json();
  assert.equal(response.status, expected, `${method} ${path}: expected ${expected}, received ${response.status}: ${JSON.stringify(data)}`);
  return data;
 };
}
